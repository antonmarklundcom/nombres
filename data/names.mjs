// ---- helpers (determinísticos) ----
export function slugify(s) {
  return s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

// Contador de sílabas aproximado para español (sólo para la etiqueta "corto").
function syllables(word) {
  const w = word.toLowerCase();
  const strong = 'aeoáéóíú', vowels = 'aeiouáéíóúü';
  let count = 0, prev = '';
  for (const ch of w) {
    if (vowels.includes(ch)) {
      if (!prev) count++;
      else if (strong.includes(ch) && strong.includes(prev)) count++;
      prev = ch;
    } else prev = '';
  }
  return count;
}

export const NAMES = ROWS.map(([name, gender, origin, meaning, flags, extra = {}]) => {
  const tags = [];
  if (flags.includes('c')) tags.push('clasico');
  if (flags.includes('m')) tags.push('moderno');
  const compound = name.includes(' ');
  const letters = name.replace(/[^\p{L}]/gu, '').length;
  if (!compound && (letters <= 4 || (letters <= 6 && syllables(name) === 2))) tags.push('corto');
  if (compound) tags.push('compuesto');
  if (flags.includes('b')) tags.push('biblico');
  if (origin === 'guaraní') tags.push('guarani');
  if (extra.s) tags.push('santo');
  if (gender === 'u') tags.push('unisex');
  const entry = { slug: slugify(name), name, gender, origin, meaning, tags };
  if (extra.s) entry.saint = extra.s;
  if (extra.v) entry.variants = extra.v;
  if (extra.n) entry.note = extra.n;
  return entry;
});
